def esc(s):
    return html.escape(s, quote=True)


def fig(i, caption, cls=""):
    o = M[i]
    lic = o["lic"]
    lic_html = f'<a href="{esc(o["licurl"])}">{esc(lic)}</a>' if o["licurl"] and "Public" not in lic else esc(lic)
    author = o.get("author_ru") or o["artist"]
    return (f'<figure class="{cls}"><img src="{o["file"]}" alt="{esc(caption)}" loading="lazy">'
            f'<figcaption>{caption} <span class="lic">— {esc(author)}, '
            f'{lic_html}, <a href="{esc(o["page"])}">Викисклад</a></span></figcaption></figure>')


def track(i, title, note):
    o = M[i]
    return (f'<div class="track"><b>{title}</b><span>{note}</span>'
            f'<audio controls preload="none" src="{o["file"]}"></audio>'
            f'<span class="lic">{esc(o["lic"])} · <a href="{esc(o["page"])}">страница записи на Викискладе</a></span></div>')


def side(cur):
    out = ['<nav class="side" aria-label="Указатель">',
           '<a class="brand" href="index.html" aria-label="На главную">' +
           "".join(f"<span>{c}</span>" for c in "МОРС") + "</a>",
           '<p class="brand-sub">Энциклопедия вселенной</p>']
    for head, items in NAV:
        out.append(f"<h3>{head}</h3><ul>")
        for slug, label in items:
            if slug is None:
                out.append(f'<li class="soon">{label}</li>')
            else:
                cur_attr = ' aria-current="page"' if slug == cur else ""
                out.append(f'<li><a href="{slug}.html"{cur_attr}>{label}</a></li>')
        out.append("</ul>")
    out.append("</nav>")
    return "\n".join(out)


