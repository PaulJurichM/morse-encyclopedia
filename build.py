def map_svg():
    # Схема по реальным координатам (равнопромежуточная проекция), подписи — ориентиры
    pts = {
        "Карфакс (центр)": (51.7520, -1.2577, "pt2"),
        "Джерико · «Переплётчики»": (51.7593, -1.2671, "pt"),
        "«Орёл и дитя»": (51.7570, -1.2603, "pt"),
        "Саммертаун": (51.7754, -1.2640, "pt2"),
        "Кидлингтон": (51.8230, -1.2900, "pt2"),
        "«Чёрный принц»": (51.8496, -1.3555, "pt"),
        "Бленхеймский дворец": (51.8414, -1.3611, "pt2"),
    }
    lat0, lat1, lon0, lon1 = 51.740, 51.862, -1.380, -1.180
    W, H = 760, 560
    import math
    kx = W / ((lon1 - lon0) * math.cos(math.radians(51.8)))
    ky = H / (lat1 - lat0)
    k = min(kx, ky)
    def xy(lat, lon):
        return ((lon - lon0) * math.cos(math.radians(51.8)) * k + 20, (lat1 - lat) * k + 10)
    road = [(51.7520, -1.2577), (51.7600, -1.2620), (51.7754, -1.2700), (51.7930, -1.2770),
            (51.8100, -1.2900), (51.8230, -1.3050), (51.8380, -1.3350), (51.8496, -1.3555)]
    d = "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in (xy(a, b) for a, b in road))
    s = [f'<svg viewBox="0 0 {W} {H}" role="img" aria-label="Схема: от центра Оксфорда по Вудсток-роуд до Вудстока">',
         f'<path class="road" d="{d}"/>']
    mx, my = xy(51.790, -1.278)
    s.append(f'<text class="lbl" x="{mx + 10:.0f}" y="{my:.0f}">Вудсток-роуд → A44</text>')
    for name, (la, lo, cls) in pts.items():
        x, y = xy(la, lo)
        off = {"Джерико · «Переплётчики»": (-10, -4, "end"), "«Орёл и дитя»": (10, -6, "start"),
               "Карфакс (центр)": (10, 14, "start"), "«Чёрный принц»": (10, -6, "start"),
               "Бленхеймский дворец": (10, 12, "start")}
        dx, dy, anchor = off.get(name, (10, 4, "start"))
        s.append(f'<circle class="{cls}" cx="{x:.1f}" cy="{y:.1f}" r="5.5"/>'
                 f'<text x="{x + dx:.1f}" y="{y + dy:.1f}" text-anchor="{anchor}">{name}</text>')
    # масштаб 2 км
    x1, y1 = xy(51.745, -1.370)
    x2, _ = xy(51.745, -1.370 + 2 / (111.32 * math.cos(math.radians(51.8))))
    s.append(f'<line x1="{x1:.0f}" y1="{y1:.0f}" x2="{x2:.0f}" y2="{y1:.0f}" stroke="currentColor" class="road"/>'
             f'<text class="lbl" x="{x1:.0f}" y="{y1 - 8:.0f}">2 км</text>')
    s.append(f'<text class="lbl" x="{W - 12}" y="{H - 12}" text-anchor="end">схема по координатам, север сверху</text></svg>')
    return "".join(s)


def build(out=OUT, full=True):
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(out)
    shutil.copytree("assets", f"{out}/assets")
    shutil.copytree("media", f"{out}/media")
    mp = map_svg()
    for slug, (title, body) in PAGES.items():
        body = body.replace("{MAP}", mp)
        t = title if slug == "index" else f"{title} · Вселенная Морса"
        open(f"{out}/{slug}.html", "w", encoding="utf-8").write(page(slug, t, body, full=True))
    if not full:
        css = open("assets/style.css", encoding="utf-8").read()
        for fn in os.listdir(out):
            if fn.endswith(".html"):
                t = open(f"{out}/{fn}", encoding="utf-8").read()
                open(f"{out}/{fn}", "w", encoding="utf-8").write(t.replace('<link rel="stylesheet" href="assets/style.css">', f"<style>{css}</style>"))
        title, body = PAGES["index"]
        body = body.replace("{MAP}", mp)
        open(f"{out}/index.html", "w", encoding="utf-8").write(page("index", title, body, full=False).replace('<link rel="stylesheet" href="assets/style.css">', f"<style>{css}</style>"))
    print("ok", len(PAGES), "страниц →", out)


