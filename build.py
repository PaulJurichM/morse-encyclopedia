def map_svg(spec):
    import math
    lat0, lat1, lon0, lon1 = spec["bounds"]
    W, H = 760, 560
    c = math.cos(math.radians(51.8))
    k = min(W / ((lon1 - lon0) * c), H / (lat1 - lat0))
    def xy(lat, lon):
        return ((lon - lon0) * c * k + 20, (lat1 - lat) * k + 10)
    s = [f'<svg viewBox="0 0 {W} {H}" role="img" aria-label="{spec["aria"]}">']
    for road, label, lp in spec["roads"]:
        d = "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in (xy(a, b) for a, b in road))
        mx, my = xy(*lp)
        s.append(f'<path class="road" d="{d}"/><text class="lbl" x="{mx + 10:.0f}" y="{my:.0f}">{label}</text>')
    for name, la, lo, cls, dx, dy, anchor in spec["pts"]:
        x, y = xy(la, lo)
        s.append(f'<circle class="{cls}" cx="{x:.1f}" cy="{y:.1f}" r="5.5"/>'
                 f'<text x="{x + dx:.1f}" y="{y + dy:.1f}" text-anchor="{anchor}">{name}</text>')
    sl, so, km = spec["scale"]
    x1, y1 = xy(sl, so)
    x2, _ = xy(sl, so + km / (111.32 * c))
    s.append(f'<line x1="{x1:.0f}" y1="{y1:.0f}" x2="{x2:.0f}" y2="{y1:.0f}" class="road"/>'
             f'<text class="lbl" x="{x1:.0f}" y="{y1 - 8:.0f}">{km} км</text>')
    s.append(f'<text class="lbl" x="{W - 12}" y="{H - 12}" text-anchor="end">схема по координатам, север сверху</text></svg>')
    return "".join(s)


def fill_maps(body):
    for key, spec in MAPS.items():
        body = body.replace("{" + key + "}", map_svg(spec))
    return body


def build(out=OUT, full=True):
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(out)
    shutil.copytree("assets", f"{out}/assets")
    shutil.copytree("media", f"{out}/media")
    for slug, (title, body) in PAGES.items():
        body = fill_maps(body)
        t = title if slug == "index" else f"{title} · Вселенная Морса"
        open(f"{out}/{slug}.html", "w", encoding="utf-8").write(page(slug, t, body, full=True))
    if not full:
        css = open("assets/style.css", encoding="utf-8").read()
        for fn in os.listdir(out):
            if fn.endswith(".html"):
                t = open(f"{out}/{fn}", encoding="utf-8").read()
                open(f"{out}/{fn}", "w", encoding="utf-8").write(t.replace('<link rel="stylesheet" href="assets/style.css">', f"<style>{css}</style>"))
        title, body = PAGES["index"]
        body = fill_maps(body)
        open(f"{out}/index.html", "w", encoding="utf-8").write(page("index", title, body, full=False).replace('<link rel="stylesheet" href="assets/style.css">', f"<style>{css}</style>"))
    print("ok", len(PAGES), "страниц →", out)


