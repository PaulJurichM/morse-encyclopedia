def timeline():
    x0, x1, w = 170, 900, 920
    sx = lambda y: x0 + (y - 1970) * (x1 - x0) / (2025 - 1970)
    rows = [
        ("Романы", [(1975, 1999)], [1975, 1976, 1977, 1979, 1981, 1983, 1986, 1989, 1991, 1992, 1994, 1996, 1999], False),
        ("«Инспектор Морс»", [(1987, 2000)], [], True),
        ("«Льюис»", [(2006, 2015)], [], False),
        ("«Индевор»", [(2012, 2023)], [], False),
    ]
    s = [f'<svg viewBox="0 0 {w} 190" role="img" aria-label="Шкала: романы 1975–1999, сериалы 1987–2023">']
    for y in range(1970, 2030, 5):
        X = sx(y)
        s.append(f'<line class="axis" x1="{X:.1f}" y1="18" x2="{X:.1f}" y2="160"/>'
                 f'<text x="{X:.1f}" y="176" text-anchor="middle" class="soft">{y}</text>')
    for k, (name, spans, dots, acc) in enumerate(rows):
        Y = 34 + k * 34
        s.append(f'<text x="0" y="{Y + 4}">{name}</text>')
        for a, b in spans:
            s.append(f'<rect class="bar{" acc" if acc else ""}" x="{sx(a):.1f}" y="{Y - 6}" width="{sx(b) - sx(a):.1f}" height="12"/>')
        for d in dots:
            s.append(f'<rect class="dot" x="{sx(d) - 3:.1f}" y="{Y - 9}" width="6" height="18"><title>{d}</title></rect>')
    s.append("</svg>")
    return '<div class="timeline">' + "".join(s) + "</div>"


